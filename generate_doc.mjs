const RU_LANG = "ru-RU";

function makeP(text, options = {}) {
  const {
    indent = 709, // 1.25 см красная строка
    align = AlignmentType.JUSTIFIED,
    bold = false,
    italic = false,
    spaceBefore = 0,
    spaceAfter = 120,
    size = SIZE_MAIN,
    runs = null
  } = options;

  let textRuns = [];
  if (runs) {
    textRuns = runs.map(r => new TextRun({
      text: r.text,
      font: FONT_FAMILY,
      size: r.size || size,
      bold: r.bold || false,
      italic: r.italic || false,
      language: {
        value: RU_LANG
      }
    }));
  } else {
    textRuns = [new TextRun({
      text,
      font: FONT_FAMILY,
      size,
      bold,
      italic,
      language: {
        value: RU_LANG
      }
    })];
  }

  return new Paragraph({
    alignment: align,
    indent: indent > 0 ? { firstLine: indent } : undefined,
    spacing: {
      line: LINE_SPACING,
      before: spaceBefore,
      after: spaceAfter
    },
    children: textRuns
  });
}

function makeHeading(title) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: {
      before: 300,
      after: 200,
      line: LINE_SPACING
    },
    children: [
      new TextRun({
        text: title.toUpperCase(),
        font: FONT_FAMILY,
        size: SIZE_MAIN,
        bold: true,
        language: { value: RU_LANG }
      })
    ]
  });
}

function makeSubHeading(title) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: { firstLine: 709 },
    spacing: {
      before: 200,
      after: 120,
      line: LINE_SPACING
    },
    children: [
      new TextRun({
        text: title,
        font: FONT_FAMILY,
        size: SIZE_MAIN,
        bold: true,
        language: { value: RU_LANG }
      })
    ]
  });
}

