export function convertPercentToSchoolGrade(percent) {
  if (percent >= 85) return { grade: 5, text: 'Отлично «5»', color: 'text-emerald-400', bg: 'bg-emerald-950/60 border-emerald-500/40' };
  if (percent >= 68) return { grade: 4, text: 'Хорошо «4»', color: 'text-blue-400', bg: 'bg-blue-950/60 border-blue-500/40' };
  if (percent >= 48) return { grade: 3, text: 'Удовл. «3»', color: 'text-amber-400', bg: 'bg-amber-950/60 border-amber-500/40' };
  return { grade: 2, text: 'Неуд «2»', color: 'text-rose-400', bg: 'bg-rose-950/60 border-rose-500/40' };
}

