export function generateQuestions(topicId, taskType, count = 5) {
  let pool = [];

  if (topicId === 'all') {
    // Собрать из всех тем
    Object.keys(QUESTIONS_DB).forEach(tid => {
      const topicData = QUESTIONS_DB[tid];
      if (taskType === 'all') {
        Object.keys(topicData).forEach(tt => {
          pool.push(...topicData[tt].map(q => ({ ...q, topicId: tid, taskType: tt })));
        });
      } else if (topicData[taskType]) {
        pool.push(...topicData[taskType].map(q => ({ ...q, topicId: tid, taskType })));
      }
    });
  } else {
    const topicData = QUESTIONS_DB[topicId];
    if (topicData) {
      if (taskType === 'all') {
        Object.keys(topicData).forEach(tt => {
          pool.push(...topicData[tt].map(q => ({ ...q, topicId, taskType: tt })));
        });
      } else if (topicData[taskType]) {
        pool.push(...topicData[taskType].map(q => ({ ...q, topicId, taskType })));
      } else {
        const firstType = Object.keys(topicData)[0];
        if (firstType) {
          pool.push(...topicData[firstType].map(q => ({ ...q, topicId, taskType: firstType })));
        }
      }
    }
  }

  // Shuffle and slice
  const shuffled = shuffleArray(pool);
  return shuffled.slice(0, Math.min(count, shuffled.length)).map((q, idx) => ({
    ...q,
    options: q.options ? shuffleArray(q.options) : q.options,
    id: `q_${Date.now()}_${idx}`,
    num: idx + 1
  }));
}

function shuffleArray(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

